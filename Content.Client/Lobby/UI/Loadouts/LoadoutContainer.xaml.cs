namespace Content.Client.Lobby.UI.Loadouts;

[GenerateTypedNameReferences]
public sealed partial class LoadoutContainer : BoxContainer
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _protoManager = default!;

    // LoneStar: Track colorable preview state for the selected loadout.
    private EntityUid? _entity;
    private readonly EntProtoId? _previewEntityProto;
    private readonly Loadout? _selectedLoadout;
    private readonly Action? _onColorsChanged;
    private readonly Dictionary<string, Dictionary<string, Color>> _palettes = new();
    private bool _hasVariants;
    private ColorableClothingSystem? _colorableSystem;
    private ColorizerWindow? _colorizerWindow;

    public Button Select => SelectButton;
    public bool CanColorize => _selectedLoadout != null && (_palettes.Count > 0 || _hasVariants);

    public string? Text
    {
        get => SelectButton.Text;
        set => SelectButton.Text = value;
    }

    // LoneStar: Provide selected state and change notification to the color editor.
    public LoadoutContainer(ProtoId<LoadoutPrototype> proto, bool disabled, FormattedMessage? reason,
        Loadout? selectedLoadout = null, Action? onColorsChanged = null)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _selectedLoadout = selectedLoadout;
        _onColorsChanged = onColorsChanged;

        SelectButton.Disabled = disabled;

        if (disabled && reason != null)
        {
            var tooltip = new Tooltip();
            tooltip.SetMessage(reason);
            SelectButton.TooltipSupplier = _ => tooltip;
        }

        if (_protoManager.TryIndex(proto, out var loadProto))
        {
            // Frontier: overrideable prototype fields (description, name, icon [via entity])
            Price.Text = "$" + loadProto.Price;

            bool hasDescription = !string.IsNullOrEmpty(loadProto.Description);
            bool hasEntity = !string.IsNullOrEmpty(loadProto.PreviewEntity?.Id);

            EntProtoId? ent = null;
            if (!hasEntity || !hasDescription) {
                ent = _entManager.System<LoadoutSystem>().GetFirstOrNull(loadProto);
            }
            var finalEnt = hasEntity ? loadProto.PreviewEntity : ent;
            // LoneStar start, Keep the preview entity available for color editing.
            if (finalEnt is { } previewProto)
            {
                _previewEntityProto = previewProto;
                SpawnPreviewEntity();

                var spriteTooltip = new Tooltip();
                var description = hasDescription ? loadProto.Description : _entManager.GetComponent<MetaDataComponent>(_entity!.Value).EntityDescription;
                spriteTooltip.SetMessage(FormattedMessage.FromUnformatted(description));
                Sprite.TooltipSupplier = _ => spriteTooltip; // Frontier: TooltipSupplier<Sprite.TooltipSupplier?
            }

            if (loadProto.Tags.Contains(LoadoutPrototype.ColorableTag) &&
                _entity != null &&
                _selectedLoadout != null &&
                _entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var colorable))
            {
                SetupColorEditor(colorable);
            }
            // LoneStar end
            // End Frontier
        }
    }

    // LoneStar start, loadout preview color and layer variant editing.
    private void SetupColorEditor(ColorableClothingComponent colorable)
    {
        _palettes.Clear();
        _hasVariants = false;
        foreach (var (key, paletteId) in colorable.MappedColors)
        {
            if (_protoManager.TryIndex<ColorPalettePrototype>(paletteId, out var palette))
                _palettes[key] = palette.Colors;
        }

        var availableVariants = new Dictionary<string, HashSet<string>>();
        foreach (var group in colorable.Available)
        {
            foreach (var (layer, states) in group)
            {
                if (!availableVariants.TryGetValue(layer, out var variants))
                {
                    variants = new HashSet<string>();
                    availableVariants.Add(layer, variants);
                }

                variants.UnionWith(states.Keys);
            }
        }

        _hasVariants = availableVariants.Values.Any(variants => variants.Count > 1);
        _colorableSystem = _entManager.System<ColorableClothingSystem>();
        _colorableSystem.ApplyInitialVariants(_entity!.Value, colorable, _selectedLoadout!.InitialVariants);
        _colorableSystem.ApplyInitialColors(_entity!.Value, colorable, _selectedLoadout!.InitialColors);
    }

    public void OpenColorEditor()
    {
        if (!CanColorize ||
            _entity == null ||
            !_entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var colorable))
            return;

        var state = GetColorizerState();
        if (_colorizerWindow != null)
        {
            _colorizerWindow.UpdateState(state, _entity, allowRandomize: false);
            _colorizerWindow.OpenCentered();
            return;
        }

        var window = new ColorizerWindow();
        _colorizerWindow = window;
        window.UpdateState(state, _entity, allowRandomize: false);
        window.OnColorSelected += (key, name) =>
        {
            if (!_palettes.TryGetValue(key, out var palette) || !palette.TryGetValue(name, out var color))
                return;

            _selectedLoadout!.InitialColors[key] = color;
            if (_entity != null &&
                _entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var currentColorable))
            {
                _colorableSystem!.ApplyInitialColors(_entity.Value, currentColorable, _selectedLoadout.InitialColors);
            }

            _onColorsChanged?.Invoke();
        };
        window.OnVariantSelected += (layer, variant) =>
        {
            _selectedLoadout!.InitialVariants[layer] = variant;
            if (_entity != null &&
                _entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var currentColorable))
            {
                _colorableSystem!.ApplyInitialVariants(_entity.Value, currentColorable, _selectedLoadout.InitialVariants);
                _colorableSystem.ApplyInitialColors(_entity.Value, currentColorable, _selectedLoadout.InitialColors);
                window.UpdateState(GetColorizerState(), _entity, allowRandomize: false);
            }

            _onColorsChanged?.Invoke();
        };
        window.OnClose += () => _colorizerWindow = null;
        window.OpenCentered();
    }

    private ColorizerBoundUserInterfaceState GetColorizerState()
    {
        var colors = _selectedLoadout!.InitialColors;
        var activeColors = new Dictionary<string, Color>();
        var activeColorNames = new Dictionary<string, string>();
        var availableVariants = new Dictionary<string, List<string>>();
        var selectedVariants = new Dictionary<string, string>();

        if (_entity != null &&
            _entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var colorable))
        {
            foreach (var group in colorable.Available)
            {
                foreach (var (layer, states) in group)
                {
                    if (!availableVariants.TryGetValue(layer, out var variants))
                    {
                        variants = new List<string>();
                        availableVariants.Add(layer, variants);
                    }

                    foreach (var variant in states.Keys)
                    {
                        if (!variants.Contains(variant))
                            variants.Add(variant);
                    }
                }
            }

            foreach (var group in colorable.Available)
            {
                foreach (var (layer, states) in group)
                {
                    if (colorable.Selected.TryGetValue(layer, out var selected))
                        selectedVariants[layer] = selected.State;
                    else if (!selectedVariants.ContainsKey(layer) && states.Count > 0)
                        selectedVariants[layer] = states.Keys.First();
                }
            }
        }

        foreach (var (key, palette) in _palettes)
        {
            if (!colors.TryGetValue(key, out var active))
                continue;

            foreach (var (name, color) in palette)
            {
                if (color != active)
                    continue;

                activeColors[key] = active;
                activeColorNames[key] = name;
                break;
            }
        }

        return new ColorizerBoundUserInterfaceState(
            default,
            _palettes,
            activeColors,
            activeColorNames,
            availableVariants,
            selectedVariants);
    }

    public void WipeColors()
    {
        if (!CanColorize || _previewEntityProto == null)
            return;

        _selectedLoadout!.InitialColors.Clear();
        _selectedLoadout.InitialVariants.Clear();
        if (_entity != null)
            _entManager.DeleteEntity(_entity.Value);

        SpawnPreviewEntity();
        if (_entity != null && _entManager.TryGetComponent<ColorableClothingComponent>(_entity.Value, out var colorable))
            SetupColorEditor(colorable);

        if (_colorizerWindow != null && _entity != null)
            _colorizerWindow.UpdateState(GetColorizerState(), _entity, allowRandomize: false);

        _onColorsChanged?.Invoke();
    }

    private void SpawnPreviewEntity()
    {
        if (_previewEntityProto == null)
            return;

        _entity = _entManager.SpawnEntity(_previewEntityProto, MapCoordinates.Nullspace);
        Sprite.SetEntity(_entity);
    }
    // LoneStar end

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing)
            return;

        // LoneStar;
        _colorizerWindow?.Close();
        _colorizerWindow = null;

        // LoneStar: Dispose the recreated preview entity.
        if (_entity != null)
            _entManager.DeleteEntity(_entity.Value);
    }
}
